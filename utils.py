def add(a, b):
    """
    add two numbers
    """
    return a + b

def sub(a, b):
    """
    subtrcts two numbers
    """
    return a - b

def mul(a, b):
    """
    mutiply two numbers
    """
    return a * b

def div(a, b):
    """
    divide two numbers
    """
    return a / b

def power(a, b):
    return a ** b

     